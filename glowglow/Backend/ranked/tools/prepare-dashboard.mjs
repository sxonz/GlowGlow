import { readFile, mkdir, writeFile } from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const handler = await readFile(new URL('supabase/functions/ranked/handler.mjs', root), 'utf8');
const entry = await readFile(new URL('supabase/functions/ranked/index.ts', root), 'utf8');
await mkdir(new URL('dashboard/', root), {recursive:true});
await writeFile(new URL('dashboard/index.ts', root), '// Generated by npm run dashboard. Edit handler.mjs / index.ts instead.\n// @ts-nocheck\n' + handler + '\n' + entry.replace(/^import[^\n]+\n/, ''));
console.log('dashboard/index.ts 준비 완료: Supabase 편집기에 전체 내용을 붙여넣으세요.');
